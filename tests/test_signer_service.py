def test_hmac_refusals_have_fixed_codes(e):
    body = {"client_request_id": "client-req-0001"}
    raw = json.dumps(body).encode()
    ok = auth.client_headers(KEY, "POST", "/v1/requests/order", raw, timestamp=T0, nonce="n" * 20)
    cases = [
        ({}, "AUTH_MISSING", 401),
        ({**ok, "X-FCB-Signature": "0" * 64}, "AUTH_SIGNATURE_INVALID", 401),
        ({**ok, "X-FCB-Key-Id": "mcp-other"}, "AUTH_SIGNATURE_INVALID", 401),  # no key-id oracle
        ({**ok, "X-FCB-Nonce": "short"}, "AUTH_MALFORMED", 401),
    ]
    for headers, code, status in cases:
        r = e.client.post("/v1/requests/order", content=raw, headers=headers)
        assert (r.status_code, r.json()) == (status, {"error": code}), code
    # body tampered after signing / path tampered after signing
    r = e.client.post("/v1/requests/order", content=raw + b" ", headers=ok)
    assert r.json() == {"error": "AUTH_SIGNATURE_INVALID"}
    r = e.client.post("/v1/requests/cancel", content=raw, headers=ok)
    assert r.json() == {"error": "AUTH_SIGNATURE_INVALID"}


