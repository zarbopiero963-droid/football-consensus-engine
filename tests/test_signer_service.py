def _sub(code, env):
    base = {k: v for k, v in os.environ.items() if not k.startswith(("SXBET_", "RENDER")) and k != "DATABASE_URL"}
    return subprocess.run([sys.executable, "-c", code], env={**base, "PYTHONPATH": str(ROOT), **env},
                          capture_output=True, text=True, timeout=60, cwd=str(ROOT))


