class Clock:
    def __init__(self):
        self.t = T0

    def __call__(self):
        return self.t


class Env:
    """A service + client on one state dir; `restart()` models a new process on the same disk."""

    def __init__(self, tmp_path, *, limits=True, env=None, **cfg):
        self.tmp, self.clock, self.n = tmp_path, Clock(), 0
        self.owner = Ed25519PrivateKey.generate()  # THROWAWAY owner key
        self.risk = write_risk_config(tmp_path / "risk.json", self.owner) if limits else None
        self.market = SimulatedMarketData(simulated_market(), self.clock)
        self.cfg = dict(state_dir=str(tmp_path / "state"), owner_public_key=pub(self.owner),
                        hmac_keys=(KEY, READ_ONLY), account_id="sx-dev-account", risk_config_path=self.risk)
        self.cfg.update(cfg)
        self.env = env if env is not None else {}
        self.start()

    def start(self):
        self.svc = SignerService(ServiceConfig(**self.cfg), self.market, clock=self.clock, env=self.env)
        # https base URL: the approval session cookie is Secure, so the test client only returns it over https.
        self.client = TestClient(build_app(self.svc), base_url="https://127.0.0.1:8787")

    def restart(self):
        self.svc.close()
        self.start()

    def signed(self, method, path, body=None, *, key=KEY, ts=None, nonce=None, headers_override=None):
        self.n += 1
        raw = b"" if body is None else (body if isinstance(body, bytes) else json.dumps(body).encode())
        h = auth.client_headers(key, method, path, raw, timestamp=self.clock.t if ts is None else ts,
                                nonce=nonce or f"nonce-{self.n:012d}-x")
        h.update(headers_override or {})
        return self.client.request(method, path, content=raw, headers={**h, "Content-Type": "application/json"})

    def order(self, cid="client-req-0001", **over):
        body = {"client_request_id": cid, "network": "testnet", "market_hash": DEV_MARKET_HASH, "outcome": 1,
                "stake_base_units": "1000000", "percentage_odds_limit": str(40 * 10 ** 18), "time_in_force": "GTC",
                "order_ttl_seconds": 600}
        body.update(over)
        return self.signed("POST", "/v1/requests/order", body)

    def enroll(self, passkey=None):
        passkey = passkey or FakePasskey()
        code = self.svc.issue_enrollment_code()
        opt = self.client.post("/enroll/options", json={"enrollment_code": code}).json()
        from signer.webauthn import b64url_decode
        reg = passkey.register(b64url_decode(opt["challenge"]))
        r = self.client.post("/enroll/finish", json={"challenge_id": opt["challenge_id"], **to_wire(reg)})
        assert r.status_code == 200, r.text
        self.passkeys = getattr(self, "passkeys", []) + [passkey]
        return passkey

    def unlock(self, passkey, rid, **kw):
        """Owner unlock: passkey assertion over an opaque server challenge -> session cookie for `rid`."""
        from signer.webauthn import b64url_decode
        o = self.client.post(f"/approve/{rid}/unlock/options").json()
        parts = passkey.assert_(b64url_decode(o["challenge"]), **kw)
        return self.client.post(f"/approve/{rid}/unlock", json={"unlock_id": o["unlock_id"], **to_wire(parts)})

    def view(self, rid, passkey=None):
        if passkey is not None:
            assert self.unlock(passkey, rid).status_code == 200
        return self.client.get(f"/approve/{rid}/challenge").json()

    def assertion(self, passkey, rid, decision="APPROVE", challenge=None, **kw):
        from signer.webauthn import b64url_decode
        v = self.view(rid, passkey)
        chal = challenge or b64url_decode(v["challenge_approve" if decision == "APPROVE" else "challenge_reject"])
        return {"decision": decision, **to_wire(passkey.assert_(chal, **kw))}

    def approve(self, passkey, rid, **kw):
        return self.client.post(f"/approve/{rid}/assertion", json=self.assertion(passkey, rid, **kw))


