# ---------------------------------------------------------------- structural guards (added, never relaxed)
SERVICE_FILES = sorted((ROOT / "signer_service").rglob("*.py"))
OUTBOUND = ("httpx", "requests", "urllib", "urllib3", "aiohttp", "websockets", "socket", "ssl", "http",
            "subprocess", "importlib", "bridge", "web3", "ftplib", "smtplib", "telnetlib", "asyncio")


def _imports(path):
    out = set()
    for n in ast.walk(ast.parse(path.read_text(encoding="utf-8"))):
        if isinstance(n, ast.Import):
            out.update(a.name for a in n.names)
        elif isinstance(n, ast.ImportFrom) and n.module and n.level == 0:
            out.add(n.module)
    return out


def test_signer_service_has_no_outbound_client():
    assert SERVICE_FILES
    for p in SERVICE_FILES:
        for m in _imports(p):
            assert m.split(".")[0] not in OUTBOUND, (p, m)
        tree = ast.parse(p.read_text(encoding="utf-8"))
        assert not any(isinstance(n, ast.Name) and n.id == "__import__" for n in ast.walk(tree)), p
        src = p.read_text(encoding="utf-8")
        for needle in ("create_connection", ".post(", ".put(", ".delete(", "fetch(", "heartbeat", "api.sx.bet",
                       "toronto.sx.bet", "urlopen"):
            assert needle not in src, (p, needle)


def test_signer_service_has_no_sender_and_never_enables_the_gateway():
    for p in SERVICE_FILES:
        tree = ast.parse(p.read_text(encoding="utf-8"))
        names = {n.id for n in ast.walk(tree) if isinstance(n, ast.Name)} | \
                {n.attr for n in ast.walk(tree) if isinstance(n, ast.Attribute)}
        assert not names & {"RestSender", "OfficialRestAdapter", "SubmissionTransport", "CancellationService",
                            "submit", "submit_batch", "submit_orders", "send"}, (p, names & {"RestSender"})
        for cls in (n for n in ast.walk(tree) if isinstance(n, ast.ClassDef)):
            methods = {f.name for f in cls.body if isinstance(f, (ast.FunctionDef, ast.AsyncFunctionDef))}
            assert not methods & {"send", "submit_orders", "get_fills"}, (p, cls.name)
        for call in (n for n in ast.walk(tree) if isinstance(n, ast.Call)):
            fn = ast.unparse(call.func)
            if fn.endswith("SubmissionGateway"):
                kw = {k.arg: k.value for k in call.keywords}
                assert isinstance(kw.get("transport"), ast.Constant) and kw["transport"].value is None, p
            if fn.endswith("load_live_trading_flag"):
                assert isinstance(call.args[0], ast.Constant) and call.args[0].value is None, p
            if fn.endswith("environ.get") or fn.endswith("env.get"):
                assert not (call.args and ast.unparse(call.args[0]) in ("KEY_ENV", "'SXBET_SIGNER_PRIVATE_KEY'")), p


