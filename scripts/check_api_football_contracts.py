"""API-FOOTBALL contract registry checks, coverage report and offline ingestion.

  python scripts/check_api_football_contracts.py check
  python scripts/check_api_football_contracts.py report --write
  python scripts/check_api_football_contracts.py ingest --source FILE --source-url URL --method TEXT

`ingest` reads a locally saved official source (OpenAPI JSON or Redoc HTML),
stores only the normalized contract as a snapshot, and reports a semantic diff.
It never edits the registry and never makes network calls.

Exit codes: 0 ok, 1 registry problems, 3 DOCUMENTATION_UNAVAILABLE, 4 blocking changes.
"""
from __future__ import annotations

import argparse
import asyncio
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from bridge.api_football import contracts, registry  # noqa: E402

DOCS = registry.REGISTRY_DIR
SNAPSHOTS = DOCS / "snapshots"
REPORTS = DOCS / "reports"
COVERAGE_JSON = DOCS / "coverage_matrix.json"
COVERAGE_MD = REPORTS / "coverage_report.md"


def tool_problems(raw: dict) -> list[str]:
    """Reconcile the tools a fresh MCP server would expose with the registry."""
    from mcp.server import MCPServer
    from bridge.api_football.tools import register

    server = MCPServer("contract-check")
    register(server)
    tools = {tool.name: tool for tool in asyncio.run(server.list_tools())}
    problems = []
    params = raw["parameters"]["endpoints"]
    expected = {}
    for endpoint in raw["endpoints"]["endpoints"]:
        if endpoint.get("mcp_tool"):
            expected[endpoint["mcp_tool"]] = {item["name"] for item in params[endpoint["id"]]["params"]}
    local = {"apifootball_health", "apifootball_quota_report", "apifootball_endpoint_registry"}
    for name, names in expected.items():
        if name not in tools:
            problems.append(f"missing tool {name}")
            continue
        exposed = set(tools[name].input_schema.get("properties", {})) - {"use_cache"}
        if exposed - names:
            problems.append(f"{name}: parameters without contract: {sorted(exposed - names)}")
        if names - exposed:
            problems.append(f"{name}: registry parameters not implemented: {sorted(names - exposed)}")
    for name in set(tools) - set(expected) - local:
        problems.append(f"tool without contract: {name}")
    return problems


def snapshot_problems() -> list[str]:
    problems = []
    for path in sorted(SNAPSHOTS.glob("*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        if contracts.sha256(data.get("contract")) != data.get("normalized_sha256"):
            problems.append(f"snapshot {path.name}: normalized_sha256 mismatch")
    return problems


def render_markdown(cov: dict) -> str:
    d = cov["dashboard"]

    def ratio(item):
        return f"{item['numerator']}/{item['denominator']}"

    lines = [
        "# API-FOOTBALL coverage report",
        "",
        "Generated by `scripts/check_api_football_contracts.py report --write` from the registry. Do not edit.",
        "",
        "| Indicator | Value | Note |",
        "| --- | --- | --- |",
        f"| Endpoints catalogued | {d['endpoints_catalogued']['value']} | {d['endpoints_catalogued']['denominator_note']} |",
        f"| Official contracts verified | {ratio(d['official_contracts_verified'])} | official documentation unavailable |",
        f"| Owner-verified parameter names | {ratio(d['owner_verified_parameter_names'])} | names only |",
        f"| Endpoints implemented as MCP tools | {ratio(d['endpoints_implemented_as_tools'])} | provisional client validation |",
        f"| Parameters covered | {ratio(d['parameters_covered'])} | {d['parameters_covered']['denominator_note']} |",
        f"| Response schemas verified | {ratio(d['response_schemas_verified'])} | |",
        f"| Mock tests | see CI | `{registry.MOCK_TEST}` |",
        f"| Real tests passed | {ratio(d['real_tests_passed'])} | REAL_API_TEST_NOT_AUTHORIZED |",
        f"| Incomplete contracts | {d['incomplete_contracts']['value']} | |",
        f"| Breaking changes detected | {d['breaking_changes_detected']['value']} | {d['breaking_changes_detected']['note']} |",
        "| Browser regressions | must be 0 | enforced by `tests/api_football/test_compatibility.py` |",
        "",
        "| Id | Path | MCP tool | Parameters | Contract | Implementation | Real test |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for row in cov["endpoints"]:
        lines.append(f"| {row['id']} | `{row['path']}` | {row['mcp_tool'] or '—'} | {row['parameter_status']} | "
                     f"{row['contract_status']} | {row['implementation_status']} | {row['real_test_status']} |")
    return "\n".join(lines) + "\n"


def coverage_outputs() -> dict[Path, str]:
    cov = registry.coverage()
    return {COVERAGE_JSON: json.dumps(cov, indent=2, ensure_ascii=False) + "\n", COVERAGE_MD: render_markdown(cov)}


def cmd_check(_args) -> int:
    raw = registry.load_raw()
    problems = registry.check(raw)
    if not problems:
        problems += tool_problems(raw)
    problems += snapshot_problems()
    for path, text in coverage_outputs().items():
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            problems.append(f"{path.relative_to(ROOT)} is stale; run: report --write")
    cov = registry.coverage(raw) if not registry.check(raw) else None
    print(json.dumps({"ok": not problems, "problems": problems,
                      "dashboard": cov["dashboard"] if cov else None}, indent=2))
    return 1 if problems else 0


def cmd_report(args) -> int:
    outputs = coverage_outputs()
    if args.write:
        REPORTS.mkdir(parents=True, exist_ok=True)
        for path, text in outputs.items():
            path.write_text(text, encoding="utf-8")
    sys.stdout.write(outputs[COVERAGE_MD])
    return 0


def cmd_ingest(args) -> int:
    text = Path(args.source).read_text(encoding="utf-8", errors="replace")
    try:
        spec = contracts.extract_spec(text)
    except (contracts.DocumentationUnavailable, ValueError) as exc:
        # Keep the last verified snapshot; never treat unavailability as removal.
        print(json.dumps({"status": "DOCUMENTATION_UNAVAILABLE", "reason": str(exc) or type(exc).__name__,
                          "registry_modified": False, "snapshot_written": False}, indent=2))
        return 3
    normalized = contracts.normalize_openapi(spec)
    acquired = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    snap = contracts.snapshot(normalized, args.source_url, acquired, args.method)
    previous = [json.loads(path.read_text(encoding="utf-8")) for path in SNAPSHOTS.glob("*.json")]
    against_previous = None
    if previous:
        latest = max(previous, key=lambda item: item["acquired_at_utc"])
        against_previous = contracts.summarize(contracts.diff(latest["contract"], normalized))
    against_registry = contracts.summarize(contracts.diff(contracts.registry_view(registry.load_raw()), normalized))
    name = f"{acquired[:10]}_{snap['normalized_sha256'][:12]}"
    SNAPSHOTS.mkdir(parents=True, exist_ok=True)
    REPORTS.mkdir(parents=True, exist_ok=True)
    (SNAPSHOTS / f"{name}.json").write_text(json.dumps(snap, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    report = {"status": "SNAPSHOT_WRITTEN", "snapshot": f"snapshots/{name}.json",
              "normalized_sha256": snap["normalized_sha256"], "endpoint_count": snap["endpoint_count"],
              "info_version": (spec.get("info") or {}).get("version"), "registry_modified": False,
              "against_previous_snapshot": against_previous, "against_registry": against_registry}
    (REPORTS / f"change_report_{name}.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({key: report[key] for key in ("status", "snapshot", "normalized_sha256", "endpoint_count")}
                     | {"registry_counts": against_registry["counts"], "blocking": against_registry["blocking"]},
                     indent=2))
    return 4 if against_registry["blocking"] or (against_previous or {}).get("blocking") else 0


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("check").set_defaults(func=cmd_check)
    report = sub.add_parser("report")
    report.add_argument("--write", action="store_true")
    report.set_defaults(func=cmd_report)
    ingest = sub.add_parser("ingest")
    ingest.add_argument("--source", required=True)
    ingest.add_argument("--source-url", required=True)
    ingest.add_argument("--method", required=True, help="how the source was acquired, e.g. 'owner browser save'")
    ingest.set_defaults(func=cmd_ingest)
    args = parser.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())
